  await page.locator('[data-pc-input-ok]').click();
  expect((await restoreResponse).status()).toBe(200);
  await expect(rows).toHaveCount(1); await expect(rows.first()).not.toContainText('已移除');
  const restored = (await (await page.request.get(`/api/v1/organizations/${id}`)).json()).data;
