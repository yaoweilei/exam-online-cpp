const { test, expect } = require('@playwright/test');
const { loginWithPassword, loginApi, uniqueLoginId } = require('./helpers/session');
const fs = require('node:fs');
const path = require('node:path');
const output = path.resolve(__dirname, '../../artifacts/support-categories-20261103');
fs.mkdirSync(output, { recursive: true });

test('客服服务说明不可误点，账号支付专用反馈可真实提交、受理和回复', async ({ page, request }) => {
  await loginWithPassword(page, uniqueLoginId('student_support_categories'));
  await page.evaluate(() => window.openPersonalCenter());
  await page.waitForLoadState('networkidle');
  await page.locator('[data-platform-admin-account-menu]').click();
  await page.locator('[data-account-destination=student-account-feedback]').click();
  const shell = page.locator('#platform-admin-shell');
  const generalLink = '[data-intent="openRoleContent:support-feedback"]';
  await shell.locator(generalLink).click();
  const form = shell.locator('[data-support-feedback-form]');
  await expect(form.locator('[data-support-feedback-description]')).toHaveValue('');
  await form.locator('[data-support-feedback-paper-id]').fill('2023_02');
  await form.locator('[data-support-feedback-question-id]').fill('29');
  await form.locator('[data-support-feedback-description]').fill('题目反馈的独立草稿');
  await shell.locator('[data-workspace-back]').click();
  await shell.locator('[data-intent="openRoleContent:support-customer-service"]').click();
  const services = shell.locator('[aria-label="客服服务"]');
  await expect(services.locator('.pc-grouped-heading')).toHaveCount(0);
  await expect(services.getByRole('button')).toHaveCount(1);
  await expect(services.locator('.pc-lite-row-static')).toContainText('暂未接入在线会话');
  await expect(services).not.toContainText('可用');
  await page.setViewportSize({ width: 540, height: 900 });
  await page.screenshot({ path: path.join(output, 'customer-service-540.png') });
  await services.locator('[data-intent="openRoleContent:support-account-payment"]').click();
  await expect(shell.getByRole('heading', { name: '账号与支付问题', exact: true })).toBeVisible();
  await expect(form).toHaveAttribute('data-feedback-mode', 'account-payment');
  await expect(form.locator('[data-support-feedback-category] option')).toHaveCount(2);
  await expect(form.locator('[data-support-feedback-category]')).toHaveValue('account');
  await expect(form.locator('[data-support-feedback-question-fields]')).toBeHidden();
  await expect(form.locator('[data-support-feedback-description]')).toHaveValue('');
  await form.locator('button[type=submit]').click();
  await expect(form.locator('[data-support-feedback-description]')).toHaveAttribute('aria-invalid', 'true');
  const description = `账号登录问题_${Date.now()}`;
  await form.locator('[data-support-feedback-description]').fill(description);
  for (const width of [360, 540, 768]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await shell.locator('main').evaluate(e => e.scrollWidth - e.clientWidth)).toBeLessThanOrEqual(1);
    await page.screenshot({ path: path.join(output, `account-feedback-${width}.png`) });
  }
  const response = page.waitForResponse(r => r.url().endsWith('/api/v1/feedback') && r.request().method() === 'POST');
  await form.locator('button[type=submit]').click();
  const result = await (await response).json();
  expect(result.code).toBe('OK');
  expect(result.data.category).toBe('account');
  expect(result.data.paper_id).toBe('');
  expect(result.data.question_id).toBe('');
  await expect(page.locator('#pc-toast')).toContainText('反馈已提交');
  await form.locator('[data-support-feedback-category]').selectOption('payment');
  await expect(form.locator('[data-support-feedback-question-fields]')).toBeHidden();
  await form.locator('[data-support-feedback-description]').fill('订单付款成功后套餐未生效，订单号 test_order_20261103');
  const paymentResponse = page.waitForResponse(r => r.url().endsWith('/api/v1/feedback') && r.request().method() === 'POST');
  await form.locator('button[type=submit]').click();
  const paymentResult = await (await paymentResponse).json();
  expect(paymentResult.code).toBe('OK');
  expect(paymentResult.data.category).toBe('payment');
  expect(paymentResult.data.exam_id).toBe('');
  await shell.locator('[data-workspace-back]').click();
  await expect(services).toBeVisible();
  await shell.locator('[data-workspace-back]').click();
  await shell.locator(generalLink).click();
  await expect(form.locator('[data-support-feedback-category]')).toHaveValue('question');
  await expect(form.locator('[data-support-feedback-description]')).toHaveValue('题目反馈的独立草稿');
  await expect(form.locator('[data-support-feedback-question-fields]')).toBeVisible();
  await form.locator('[data-support-feedback-category]').selectOption('payment');
  await expect(form.locator('[data-support-feedback-question-fields]')).toBeHidden();
  await form.locator('[data-support-feedback-category]').selectOption('question');
  await expect(form.locator('[data-support-feedback-question-fields]')).toBeVisible();
  await expect(form.locator('[data-support-feedback-paper-id]')).toHaveValue('2023_02');
  // Normal content reports must still identify the question.
  const invalid = await page.request.post('/api/v1/feedback', { data: { category: 'question', description: '不能省略题目上下文', paper_id: '', question_id: '' } });
  expect(invalid.status()).toBe(422);
  await loginApi(request, uniqueLoginId('superadmin_support_categories'));
  const id = result.data.feedback_id;
  const context = await request.get(`/api/v1/feedback/${id}/context`);
  expect(context.ok()).toBeTruthy();
  expect((await context.json()).data.source_available).toBe(false);
  const update = await request.patch(`/api/v1/feedback/${id}`, { data: { status: 'resolved', public_reply: '已受理并处理该账号问题' } });
  expect(update.ok()).toBeTruthy();
  const replies = (await (await page.request.get('/api/v1/me/feedback-results')).json()).data;
  expect(replies.find(item => item.feedback_id === id).public_reply).toBe('已受理并处理该账号问题');
});
